import { relative } from 'node:path';

import type { ApiConfig } from '@rn-tempo/api-contract';

import { buildOpenApi, type OpenApiOptions } from './openapi.ts';
import { buildPostmanCollection, buildPostmanEnvironment } from './postman.ts';

export const OPENAPI_FILE = 'openapi.json';
export const POSTMAN_COLLECTION_FILE = 'postman.collection.json';
export const POSTMAN_ENVIRONMENT_FILE = 'postman.environment.json';
export const MSW_FILE = 'msw-handlers.ts';

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;

/** The OpenAPI file's text. */
export function openapiFiles(config: ApiConfig, options?: OpenApiOptions): Record<string, string> {
  return { [OPENAPI_FILE]: json(buildOpenApi(config, options)) };
}

/** The Postman collection and environment, built from the same document as the OpenAPI file. */
export function collectionFiles(config: ApiConfig, options?: OpenApiOptions): Record<string, string> {
  const document = buildOpenApi(config, options);
  const port = config.port;
  const postman = { baseUrl: `http://localhost:${port}` };
  return {
    [POSTMAN_COLLECTION_FILE]: json(buildPostmanCollection(document, postman)),
    [POSTMAN_ENVIRONMENT_FILE]: json(buildPostmanEnvironment(postman)),
  };
}

/**
 * The MSW handlers file. It is a few lines because the work is in `toMswHandlers`; generating it
 * (instead of asking people to write it) keeps its import path to the config right and lets
 * `api:check` notice when somebody edits it by hand.
 */
export function mswFiles(configPath: string, outDir: string): Record<string, string> {
  let specifier = relative(outDir, configPath).replaceAll('\\', '/');
  specifier = specifier.replace(/\.(ts|mts|cts|js|mjs|cjs)$/, '');
  if (!specifier.startsWith('.')) specifier = `./${specifier}`;
  const text = `// AUTO-GENERATED by \`tempo-api msw\` from the endpoint definitions. Do not edit it; run \`yarn api msw\`.
import { toMswHandlers, type MswOptions } from '@rn-tempo/dev-api/runtime';
import { http, HttpResponse } from 'msw';

import config from '${specifier}';

/** MSW handlers for every endpoint, answered by the same pipeline as the dev API server. */
export function createHandlers(options?: MswOptions) {
  return toMswHandlers(config, { http, HttpResponse }, options);
}

export const handlers = createHandlers();
`;
  return { [MSW_FILE]: text };
}

/** Everything `tempo-api generate` writes, by file name. */
export function allFiles(config: ApiConfig, configPath: string, outDir: string, options?: OpenApiOptions): Record<string, string> {
  return { ...openapiFiles(config, options), ...collectionFiles(config, options), ...mswFiles(configPath, outDir) };
}
