// Embeds the exact versions of the sibling workspace packages into src/generated/versions.ts, so
// `create-tempo-app` can rewrite the template's `link:` dependencies to exact published versions.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PACKAGES = ['api-contract', 'commitlint-config', 'contracts', 'dev-api', 'eslint-config', 'prettier-config', 'tsconfig'];
// Packages that live outside packages/, as a path from the repository root. The template links the engine for
// `yarn backend` and `yarn test:backend`; like dev-api it has no published version yet, so a new project gets 0.0.0.
const OTHER_PACKAGES = ['apps/local-backend/engine'];

const dirs = [...PACKAGES.map((dir) => path.join(root, dir)), ...OTHER_PACKAGES.map((dir) => path.join(root, '..', dir))];
const entries = dirs
  .map((dir) => JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')))
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((pkg) => `  '${pkg.name}': '${pkg.version}',`);

const output = `// AUTO-GENERATED by scripts/generate-versions.mjs - do not edit.
/** Exact versions of the @rn-tempo/* workspace packages at build time. */
export const WORKSPACE_VERSIONS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

writeFileSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/generated/versions.ts'), output);
