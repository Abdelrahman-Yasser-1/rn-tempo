// Embeds the exact versions of the sibling workspace packages into src/generated/versions.ts, so
// `create-tempo-app` can rewrite the template's `link:` dependencies to exact published versions.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PACKAGES = ['commitlint-config', 'contracts', 'eslint-config', 'prettier-config', 'tsconfig'];

const entries = PACKAGES.map((dir) => {
  const pkg = JSON.parse(readFileSync(path.join(root, dir, 'package.json'), 'utf8'));
  return `  '${pkg.name}': '${pkg.version}',`;
});

const output = `// AUTO-GENERATED by scripts/generate-versions.mjs - do not edit.
/** Exact versions of the @rn-tempo/* workspace packages at build time. */
export const WORKSPACE_VERSIONS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

writeFileSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/generated/versions.ts'), output);
