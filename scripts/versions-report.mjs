#!/usr/bin/env node
// Regenerates VERSIONS.md: every pinned dependency vs. the latest on npm, with notes for exceptions.
// Usage: node scripts/versions-report.mjs > VERSIONS.md
import { execFile } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { promisify } from 'node:util';

const run = promisify(execFile);
const NOTES = {
  typescript: 'TS 7 blocked: typescript-eslint peer `<6.1.0` (ADR-004)',
  '@babel/core': 'Babel 8 blocked: @react-native/babel-preset needs `^7.25` (ADR-013)',
  '@babel/preset-env': 'Babel 7 line (ADR-013)',
  '@babel/runtime': 'Babel 7 line (ADR-013)',
};
const manifests = {
  template: 'template/package.json',
  'root (repo tooling)': 'package.json',
  'packages/commitlint-config': 'packages/commitlint-config/package.json',
  'packages/contracts': 'packages/contracts/package.json',
};

async function latest(name) {
  try {
    return (await run('npm', ['view', name, 'version'])).stdout.trim();
  } catch {
    return '?';
  }
}

const out = [
  '# Versions',
  '',
  'Policy: **newest stable version published more than 24 hours ago** (Yarn `npmMinimalAgeGate`, ADR-011), all pinned exactly. Exceptions are explained in the Notes column and in ADRs.',
  '',
  `Generated by \`node scripts/versions-report.mjs > VERSIONS.md\` on ${new Date().toISOString().slice(0, 10)}. "Behind" means npm has a newer version; it is expected when that version is younger than 24 hours or noted below.`,
  '',
  '| Tool | Version |',
  '| --- | --- |',
  `| Node (\`.nvmrc\`) | ${readFileSync('.nvmrc', 'utf8').trim()} (LTS) |`,
  `| Yarn | ${JSON.parse(readFileSync('package.json', 'utf8')).packageManager.replace('yarn@', '')} |`,
];
for (const [label, file] of Object.entries(manifests)) {
  const pkg = JSON.parse(readFileSync(file, 'utf8'));
  const deps = Object.entries({ ...pkg.dependencies, ...pkg.devDependencies }).filter(([, v]) => !/^(workspace|link|portal):/.test(v));
  if (deps.length === 0) continue;
  const rows = await Promise.all(deps.sort(([a], [b]) => a.localeCompare(b)).map(async ([name, pinned]) => [name, pinned, await latest(name)]));
  out.push('', `## ${label}`, '', '| Package | Pinned | npm latest | Notes |', '| --- | --- | --- | --- |');
  for (const [name, pinned, newest] of rows) {
    const status = pinned === newest ? '' : 'behind';
    out.push(`| \`${name}\` | ${pinned} | ${newest} | ${[status, NOTES[name]].filter(Boolean).join(' · ')} |`);
  }
}
console.log(out.join('\n'));
