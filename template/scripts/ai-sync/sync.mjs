#!/usr/bin/env node
// Generates tool-specific AI files (Claude Code, Cursor, Copilot) from the sources in `ai/`.
// Dependency-free Node ESM. Usage: `yarn ai:sync [--tools claude,cursor,copilot] [--check] [--cwd <dir>]`.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const TOOLS = ['claude', 'cursor', 'copilot'];
/** Rules that Cursor always attaches. */
export const ALWAYS_APPLY = new Set(['architecture', 'naming', 'verification']);
/** AGENTS.md sections that are copied into the Copilot instructions. */
export const COPILOT_SECTIONS = ['Stack', 'Commands', 'Golden rules'];
export const MARKER = 'generated by tempo ai sync';

/** Header written into every generated text file. */
export function header(source) {
  return `<!-- ${MARKER} from ${source} — edit the source -->`;
}

function unquote(value) {
  const quote = value[0];
  const isQuoted = (quote === "'" || quote === '"') && value.length > 1 && value.endsWith(quote);
  return isQuoted ? value.slice(1, -1) : value;
}

/** Splits `---` frontmatter (flat `key: value` lines) from the body. */
export function parseFrontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!match) {
    return { data: {}, body: text, raw: '' };
  }
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const colon = line.indexOf(':');
    if (colon > 0 && /^[a-z][\w-]*$/i.test(line.slice(0, colon))) {
      data[line.slice(0, colon)] = unquote(line.slice(colon + 1).trim());
    }
  }
  return { data, body: text.slice(match[0].length), raw: match[0] };
}

/** Quotes a YAML scalar when it would not parse as a plain string. */
function yamlScalar(value) {
  const needsQuotes =
    /[^\w/.*]/.test(value.charAt(0)) || value.includes(': ') || value.includes(' #');
  return needsQuotes ? `'${value.replaceAll("'", "''")}'` : value;
}

/** Inserts the generated-file header after the frontmatter (or at the top without one). */
export function withHeader(text, source) {
  const { raw, body } = parseFrontmatter(text);
  const normalizedBody = body.replace(/^\n+/, '');
  return `${raw}${header(source)}\n\n${normalizedBody}`;
}

function listFiles(dir) {
  return !existsSync(dir)
    ? []
    : readdirSync(dir, { withFileTypes: true })
        .sort((a, b) => a.name.localeCompare(b.name))
        .flatMap((entry) =>
          entry.isDirectory()
            ? listFiles(path.join(dir, entry.name)).map((child) => path.join(entry.name, child))
            : [entry.name],
        );
}

const posix = (value) => value.split(path.sep).join('/');

function readText(cwd, relative) {
  return readFileSync(path.join(cwd, relative), 'utf8');
}

/** Reads the rules as `{ name, description, globs, body }`. */
function readRules(cwd) {
  return listFiles(path.join(cwd, 'ai/rules'))
    .filter((file) => file.endsWith('.md'))
    .map((file) => {
      const { data, body } = parseFrontmatter(readText(cwd, `ai/rules/${file}`));
      return {
        name: file.replace(/\.md$/, ''),
        source: `ai/rules/${file}`,
        description: data.description ?? '',
        globs: data.globs ?? '',
        body,
      };
    });
}

function claudeOutputs(cwd, out) {
  for (const file of listFiles(path.join(cwd, 'ai/skills'))) {
    const source = posix(`ai/skills/${file}`);
    const text = readText(cwd, source);
    out.set(
      posix(`.claude/skills/${file}`),
      file.endsWith('.md') ? withHeader(text, source) : text,
    );
  }
  for (const folder of ['commands', 'agents']) {
    for (const file of listFiles(path.join(cwd, `ai/${folder}`)).filter((f) => f.endsWith('.md'))) {
      const source = posix(`ai/${folder}/${file}`);
      out.set(posix(`.claude/${folder}/${file}`), withHeader(readText(cwd, source), source));
    }
  }
}

/** JSON without comments cannot carry the header; arrays of primitives stay inline (prettier style). */
export function stringifyJson(value, indent = 0) {
  const pad = '  '.repeat(indent);
  if (Array.isArray(value)) {
    const inline = `[${value.map((item) => JSON.stringify(item)).join(', ')}]`;
    if (value.every((item) => typeof item !== 'object' || item === null) && inline.length < 80) {
      return inline;
    }
    const items = value.map((item) => `${pad}  ${stringifyJson(item, indent + 1)}`);
    return `[\n${items.join(',\n')}\n${pad}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).map(
      ([key, item]) => `${pad}  ${JSON.stringify(key)}: ${stringifyJson(item, indent + 1)}`,
    );
    return entries.length > 0 ? `{\n${entries.join(',\n')}\n${pad}}` : '{}';
  }
  return JSON.stringify(value);
}

/** Claude Code expands `${VAR}`; Cursor expects `${env:VAR}`. */
function toCursorValue(value) {
  if (typeof value === 'string') {
    return value.replaceAll(/\$\{(?!env:)([A-Za-z_]\w*)\}/g, '${env:$1}');
  }
  if (Array.isArray(value)) {
    return value.map(toCursorValue);
  }
  return value && typeof value === 'object'
    ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, toCursorValue(v)]))
    : value;
}

function cursorOutputs(cwd, out, rules) {
  for (const rule of rules) {
    const lines = ['---', `description: ${yamlScalar(rule.description)}`];
    if (rule.globs) {
      lines.push(`globs: ${yamlScalar(rule.globs)}`);
    }
    lines.push(`alwaysApply: ${ALWAYS_APPLY.has(rule.name)}`, '---', '');
    out.set(
      `.cursor/rules/${rule.name}.mdc`,
      `${lines.join('\n')}\n${header(rule.source)}\n\n${rule.body.replace(/^\n+/, '')}`,
    );
  }
  if (existsSync(path.join(cwd, '.mcp.json'))) {
    const mcp = toCursorValue(JSON.parse(readText(cwd, '.mcp.json')));
    out.set('.cursor/mcp.json', `${stringifyJson(mcp)}\n`);
  }
}

/** Returns the `## <title>` sections of a markdown document. */
export function extractSections(markdown, titles) {
  const sections = new Map();
  let current;
  for (const line of markdown.split('\n')) {
    if (line.startsWith('## ')) {
      current = line.slice(3).trim();
      sections.set(current, [line]);
    } else if (current) {
      sections.get(current).push(line);
    }
  }
  return titles
    .filter((title) => sections.has(title))
    .map((title) => sections.get(title).join('\n').trimEnd());
}

function copilotOutputs(cwd, out, rules) {
  const agents = existsSync(path.join(cwd, 'AGENTS.md')) ? readText(cwd, 'AGENTS.md') : '';
  const index = rules.map(
    (rule) => `- [${rule.name}](../ai/rules/${rule.name}.md): ${rule.description}`,
  );
  const parts = [
    header('AGENTS.md and ai/rules'),
    '# Copilot instructions',
    'Condensed from [AGENTS.md](../AGENTS.md); read it for the full guide. Detailed rules are in `ai/rules/` and are also attached automatically by path (`.github/instructions/`).',
    ...extractSections(agents, COPILOT_SECTIONS),
    ['## Rules', '', ...index].join('\n'),
  ];
  out.set('.github/copilot-instructions.md', `${parts.join('\n\n')}\n`);
  for (const rule of rules) {
    const applyTo = rule.globs || '**';
    out.set(
      `.github/instructions/${rule.name}.instructions.md`,
      `---\napplyTo: '${applyTo}'\n---\n\n${header(rule.source)}\n\n${rule.body.replace(/^\n+/, '')}`,
    );
  }
}

/** Computes every generated file as a `relative path -> content` map. */
export function buildOutputs({ cwd, tools }) {
  const out = new Map();
  const rules = readRules(cwd);
  if (tools.includes('claude')) {
    claudeOutputs(cwd, out);
  }
  if (tools.includes('cursor')) {
    cursorOutputs(cwd, out, rules);
  }
  if (tools.includes('copilot')) {
    copilotOutputs(cwd, out, rules);
  }
  return out;
}

/** Generated directories per tool, used to prune files whose source was removed. */
const GENERATED_DIRS = {
  claude: ['.claude/skills', '.claude/commands', '.claude/agents'],
  cursor: ['.cursor/rules'],
  copilot: ['.github/instructions'],
};

function isGenerated(file) {
  return readFileSync(file, 'utf8').split('\n').slice(0, 15).join('\n').includes(MARKER);
}

function stale(cwd, tools, outputs) {
  const result = [];
  for (const tool of tools) {
    for (const dir of GENERATED_DIRS[tool]) {
      for (const file of listFiles(path.join(cwd, dir))) {
        const relative = posix(`${dir}/${file}`);
        if (!outputs.has(relative) && isGenerated(path.join(cwd, relative))) {
          result.push(relative);
        }
      }
    }
  }
  return result;
}

/**
 * Generates the tool files.
 * @param {{ cwd: string, tools?: string[], check?: boolean }} options
 * @returns {{ written: string[], removed: string[] }} Paths that changed (or would change with `check`).
 */
export function syncAi({ cwd, tools = TOOLS, check = false }) {
  const unknown = tools.filter((tool) => !TOOLS.includes(tool));
  if (unknown.length > 0) {
    throw new Error(`Unknown AI tool(s): ${unknown.join(', ')}. Expected: ${TOOLS.join(', ')}`);
  }
  if (!existsSync(path.join(cwd, 'ai'))) {
    throw new Error(`No ai/ folder found in ${cwd}`);
  }
  const outputs = buildOutputs({ cwd, tools });
  const written = [];
  for (const [relative, content] of outputs) {
    const target = path.join(cwd, relative);
    if (existsSync(target) && readFileSync(target, 'utf8') === content) {
      continue;
    }
    written.push(relative);
    if (!check) {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  const removed = stale(cwd, tools, outputs);
  if (!check) {
    for (const relative of removed) {
      rmSync(path.join(cwd, relative));
    }
  }
  return { written, removed };
}

/** Reads `ai.tools` from `.tempo.json`; all tools when the file or key is missing. */
export function toolsFromConfig(cwd) {
  const file = path.join(cwd, '.tempo.json');
  if (!existsSync(file)) {
    return TOOLS;
  }
  const tools = JSON.parse(readFileSync(file, 'utf8')).ai?.tools;
  return Array.isArray(tools) ? tools : TOOLS;
}

function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      args.check = true;
    } else if (arg === '--cwd' || arg === '--tools') {
      index += 1;
      args[arg.slice(2)] = argv[index];
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const cwd = path.resolve(args.cwd ?? process.cwd());
  const tools = args.tools
    ? args.tools.split(',').map((tool) => tool.trim())
    : toolsFromConfig(cwd);
  const { written, removed } = syncAi({ cwd, tools, check: Boolean(args.check) });
  for (const file of written) {
    console.log(`${args.check ? 'out of date' : 'wrote'}  ${file}`);
  }
  for (const file of removed) {
    console.log(`${args.check ? 'stale' : 'removed'}  ${file}`);
  }
  console.log(
    `ai sync (${tools.join(', ')}): ${written.length} changed, ${removed.length} removed${args.check ? ' (check only)' : ''}`,
  );
  if (args.check && written.length + removed.length > 0) {
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
