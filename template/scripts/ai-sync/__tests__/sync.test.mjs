import assert from 'node:assert/strict';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

import {
  buildOutputs,
  extractSections,
  parseFrontmatter,
  stringifyJson,
  syncAi,
  toolsFromConfig,
  withHeader,
} from '../sync.mjs';

const templateRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

function write(cwd, relative, content) {
  const target = path.join(cwd, relative);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, content);
}

const read = (cwd, relative) => readFileSync(path.join(cwd, relative), 'utf8');

function makeFixture(cwd) {
  write(
    cwd,
    'ai/rules/architecture.md',
    '---\ndescription: Layers and folders.\nglobs: src/**\n---\n\n# Architecture\n\nBody A.\n',
  );
  write(
    cwd,
    'ai/rules/testing.md',
    "---\ndescription: 'Tests: use getByRole.'\nglobs: '**/*.test.tsx'\n---\n\n# Testing\n\nBody T.\n",
  );
  write(
    cwd,
    'ai/skills/demo/SKILL.md',
    '---\nname: demo\ndescription: Demo skill.\n---\n\n# demo\n\nSteps.\n',
  );
  write(cwd, 'ai/skills/demo/notes.txt', 'plain notes\n');
  write(cwd, 'ai/commands/spec.md', '---\ndescription: Spec command\n---\n\nDo $ARGUMENTS\n');
  write(
    cwd,
    'ai/agents/reviewer.md',
    '---\nname: reviewer\ndescription: Reviews.\n---\n\nReview.\n',
  );
  write(
    cwd,
    'AGENTS.md',
    '# Guide\n\nintro\n\n## Stack\n\nRN\n\n## Other\n\nskip me\n\n## Commands\n\n| a | b |\n',
  );
  write(
    cwd,
    '.mcp.json',
    JSON.stringify({
      mcpServers: {
        gh: { type: 'http', url: 'https://x/mcp/', headers: { Authorization: 'Bearer ${TOKEN}' } },
        ctx: { command: 'npx', args: ['-y', 'pkg'] },
      },
    }),
  );
  write(cwd, '.tempo.json', JSON.stringify({ ai: { tools: ['claude', 'cursor', 'copilot'] } }));
}

describe('ai sync helpers', () => {
  it('parses flat frontmatter and strips quotes', () => {
    const { data, body } = parseFrontmatter("---\na: 1\nb: 'x y'\n---\nrest\n");
    assert.deepEqual(data, { a: '1', b: 'x y' });
    assert.equal(body, 'rest\n');
  });

  it('puts the header after the frontmatter', () => {
    const text = withHeader('---\nname: a\n---\n\nbody\n', 'ai/x.md');
    assert.equal(
      text,
      '---\nname: a\n---\n<!-- generated by tempo ai sync from ai/x.md — edit the source -->\n\nbody\n',
    );
    assert.match(
      withHeader('body\n', 'ai/y.md'),
      /^<!-- generated by tempo ai sync from ai\/y\.md — edit the source -->\n\nbody\n$/,
    );
  });

  it('extracts sections in the requested order', () => {
    const sections = extractSections('# T\n\n## B\n\nb\n\n## A\n\na\n', ['A', 'B', 'C']);
    assert.deepEqual(sections, ['## A\n\na', '## B\n\nb']);
  });

  it('keeps short primitive arrays inline', () => {
    assert.equal(stringifyJson({ a: ['x', 'y'], b: {} }), '{\n  "a": ["x", "y"],\n  "b": {}\n}');
  });
});

describe('syncAi', () => {
  let cwd;
  beforeEach(() => {
    cwd = mkdtempSync(path.join(tmpdir(), 'ai-sync-'));
    makeFixture(cwd);
  });
  afterEach(() => rmSync(cwd, { recursive: true, force: true }));

  it('writes claude, cursor and copilot outputs with headers', () => {
    const { written } = syncAi({ cwd, tools: toolsFromConfig(cwd) });
    for (const file of [
      '.claude/skills/demo/SKILL.md',
      '.claude/skills/demo/notes.txt',
      '.claude/commands/spec.md',
      '.claude/agents/reviewer.md',
      '.cursor/rules/architecture.mdc',
      '.cursor/rules/testing.mdc',
      '.cursor/mcp.json',
      '.github/copilot-instructions.md',
      '.github/instructions/architecture.instructions.md',
    ]) {
      assert.ok(written.includes(file), `${file} written`);
    }
    assert.match(
      read(cwd, '.claude/skills/demo/SKILL.md'),
      /^---\nname: demo\ndescription: Demo skill\.\n---\n<!-- generated by tempo ai sync from ai\/skills\/demo\/SKILL\.md — edit the source -->/,
    );
    assert.equal(read(cwd, '.claude/skills/demo/notes.txt'), 'plain notes\n');
    assert.match(read(cwd, '.claude/commands/spec.md'), /from ai\/commands\/spec\.md/);
  });

  it('writes cursor rules with description, globs and alwaysApply', () => {
    syncAi({ cwd });
    const architecture = read(cwd, '.cursor/rules/architecture.mdc');
    assert.match(
      architecture,
      /^---\ndescription: Layers and folders\.\nglobs: src\/\*\*\nalwaysApply: true\n---\n/,
    );
    assert.match(architecture, /<!-- generated by tempo ai sync from ai\/rules\/architecture\.md/);
    const testing = read(cwd, '.cursor/rules/testing.mdc');
    assert.match(testing, /description: 'Tests: use getByRole\.'\n/);
    assert.match(testing, /globs: \*\*\/\*\.test\.tsx\nalwaysApply: false\n/);
  });

  it('maps the mcp config to cursor env syntax', () => {
    syncAi({ cwd });
    const mcp = JSON.parse(read(cwd, '.cursor/mcp.json'));
    assert.equal(mcp.mcpServers.gh.headers.Authorization, 'Bearer ${env:TOKEN}');
    assert.deepEqual(mcp.mcpServers.ctx.args, ['-y', 'pkg']);
  });

  it('writes condensed copilot instructions and per-rule applyTo', () => {
    syncAi({ cwd });
    const main = read(cwd, '.github/copilot-instructions.md');
    assert.match(main, /## Stack\n\nRN/);
    assert.match(main, /## Commands/);
    assert.doesNotMatch(main, /skip me/);
    assert.match(
      main,
      /- \[architecture\]\(\.\.\/ai\/rules\/architecture\.md\): Layers and folders\./,
    );
    const rule = read(cwd, '.github/instructions/testing.instructions.md');
    assert.match(
      rule,
      /^---\napplyTo: '\*\*\/\*\.test\.tsx'\n---\n\n<!-- generated by tempo ai sync/,
    );
  });

  it('is idempotent: a second run changes nothing', () => {
    syncAi({ cwd });
    const second = syncAi({ cwd });
    assert.deepEqual(second, { written: [], removed: [] });
    assert.deepEqual(syncAi({ cwd, check: true }), { written: [], removed: [] });
  });

  it('check mode reports drift without writing', () => {
    const result = syncAi({ cwd, check: true });
    assert.ok(result.written.length > 0);
    assert.equal(existsSync(path.join(cwd, '.claude')), false);
  });

  it('only writes the selected tools', () => {
    syncAi({ cwd, tools: ['cursor'] });
    assert.equal(existsSync(path.join(cwd, '.cursor/rules/architecture.mdc')), true);
    assert.equal(existsSync(path.join(cwd, '.claude')), false);
    assert.equal(existsSync(path.join(cwd, '.github')), false);
  });

  it('removes stale generated files but never hand-written ones', () => {
    syncAi({ cwd });
    write(cwd, '.claude/commands/handmade.md', '# mine\n');
    rmSync(path.join(cwd, 'ai/commands/spec.md'));
    const { removed } = syncAi({ cwd });
    assert.deepEqual(removed, ['.claude/commands/spec.md']);
    assert.equal(existsSync(path.join(cwd, '.claude/commands/handmade.md')), true);
  });

  it('rejects unknown tools and a missing ai folder', () => {
    assert.throws(() => syncAi({ cwd, tools: ['vim'] }), /Unknown AI tool/);
    rmSync(path.join(cwd, 'ai'), { recursive: true });
    assert.throws(() => syncAi({ cwd }), /No ai\/ folder/);
  });

  it('falls back to all tools without .tempo.json', () => {
    rmSync(path.join(cwd, '.tempo.json'));
    assert.deepEqual(toolsFromConfig(cwd), ['claude', 'cursor', 'copilot']);
    assert.ok(buildOutputs({ cwd, tools: ['claude'] }).size > 0);
  });
});

describe('template outputs', () => {
  it('every rule, skill, command and agent has complete frontmatter', () => {
    const outputs = buildOutputs({ cwd: templateRoot, tools: ['claude', 'cursor'] });
    for (const [file, content] of outputs) {
      if (file.endsWith('SKILL.md') || file.startsWith('.claude/agents/')) {
        const { data } = parseFrontmatter(content);
        assert.ok(data.name && data.description, `${file} needs name and description`);
      }
      if (file.endsWith('.mdc')) {
        const { data } = parseFrontmatter(content);
        assert.ok(data.description, `${file} needs a description`);
      }
    }
  });

  it('committed generated files are up to date (run `yarn ai:sync`)', () => {
    const copy = mkdtempSync(path.join(tmpdir(), 'ai-sync-template-'));
    try {
      for (const entry of [
        'ai',
        'AGENTS.md',
        '.mcp.json',
        '.tempo.json',
        '.claude',
        '.cursor',
        '.github',
      ]) {
        if (existsSync(path.join(templateRoot, entry))) {
          cpSync(path.join(templateRoot, entry), path.join(copy, entry), { recursive: true });
        }
      }
      assert.deepEqual(syncAi({ cwd: copy, tools: toolsFromConfig(copy), check: true }), {
        written: [],
        removed: [],
      });
    } finally {
      rmSync(copy, { recursive: true, force: true });
    }
  });
});
