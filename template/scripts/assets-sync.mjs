// Generates the typed asset registries: src/assets/{icons,images,animations}/index.ts.
// Run with `yarn assets:sync`. The CLI's `tempo assets sync` calls the same `syncAssets` function.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = '// AUTO-GENERATED by scripts/assets-sync.mjs — do not edit';

/** Registry definitions: folder, accepted extensions, exported map and name union. */
export const REGISTRIES = [
  { dir: 'icons', extensions: ['.svg'], mapName: 'icons', typeName: 'IconName', mode: 'import' },
  {
    dir: 'images',
    extensions: ['.png', '.jpg', '.jpeg', '.webp', '.gif'],
    mapName: 'images',
    typeName: 'ImageName',
    mode: 'require',
  },
  {
    dir: 'animations',
    extensions: ['.json', '.lottie'],
    mapName: 'animations',
    typeName: 'AnimationName',
    mode: 'require',
  },
];

/** `chevron-left` -> `ChevronLeft`; leading digits get an underscore so the identifier is valid. */
export function toPascalCase(name) {
  const pascal = name
    .split(/[^a-z0-9]+/i)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
  return /^\d/.test(pascal) ? `_${pascal}` : pascal;
}

const SAFE_FILE_NAME = /^[a-z0-9][\w.-]*$/i;
const IDENTIFIER = /^[a-z_$][\w$]*$/i;

/** JSON-escaped string literal using single quotes (matches prettier, so output stays stable). */
function quote(value) {
  const escaped = JSON.stringify(value).slice(1, -1).replaceAll("'", "\\'");
  return "'" + escaped + "'";
}

/** Quotes a key only when it is not a valid identifier; the quoting is escaped, never raw. */
function toKey(name) {
  return IDENTIFIER.test(name) ? name : quote(name);
}

/** Rejects file names that could break out of the generated source. */
export function assertSafeAsset(file, name) {
  if (!SAFE_FILE_NAME.test(file)) {
    throw new Error(`assets:sync: unsafe asset file name ${JSON.stringify(file)}`);
  }
  if (!IDENTIFIER.test(toPascalCase(name))) {
    throw new Error(
      `assets:sync: asset ${JSON.stringify(file)} does not map to a valid identifier`,
    );
  }
}

/** Lists asset base names (without extension) for a registry, sorted for stable output. */
export function listAssets(folder, extensions) {
  const files = existsSync(folder) ? readdirSync(folder) : [];
  return files
    .filter((file) => extensions.includes(path.extname(file).toLowerCase()))
    .sort((a, b) => a.localeCompare(b))
    .map((file) => {
      const name = path.basename(file, path.extname(file));
      assertSafeAsset(file, name);
      return { file, name };
    });
}

/** Renders the registry source for one folder. */
export function renderRegistry(registry, assets) {
  const lines = [HEADER, ''];
  if (registry.mode === 'import') {
    for (const { file, name } of assets) {
      lines.push(`import ${toPascalCase(name)} from ${quote('./' + file)};`);
    }
    if (assets.length > 0) lines.push('');
  }
  if (assets.length === 0) {
    lines.push(`export const ${registry.mapName} = {} as const;`, '');
  } else {
    lines.push(`export const ${registry.mapName} = {`);
    for (const { file, name } of assets) {
      const value =
        registry.mode === 'import' ? toPascalCase(name) : `require(${quote('./' + file)})`;
      lines.push(`  ${toKey(name)}: ${value},`);
    }
    lines.push('} as const;', '');
  }
  lines.push(`export type ${registry.typeName} = keyof typeof ${registry.mapName};`, '');
  return lines.join('\n');
}

/**
 * Writes every registry under `<root>/src/assets`.
 * @param {string} root Project root (the folder holding package.json).
 * @returns {string[]} Paths of files whose content changed.
 */
export function syncAssets(root) {
  const changed = [];
  for (const registry of REGISTRIES) {
    const folder = path.join(root, 'src', 'assets', registry.dir);
    const target = path.join(folder, 'index.ts');
    const next = renderRegistry(registry, listAssets(folder, registry.extensions));
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== next) {
      writeFileSync(target, next);
      changed.push(target);
    }
  }
  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const changed = syncAssets(root);
  console.log(`assets:sync: ${changed.length} registries updated`);
}
