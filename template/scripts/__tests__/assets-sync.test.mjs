import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

import {
  assertSafeAsset,
  listAssets,
  renderRegistry,
  REGISTRIES,
  syncAssets,
  toPascalCase,
} from '../assets-sync.mjs';

const [icons, images] = REGISTRIES;

test('toPascalCase converts kebab names and guards leading digits', () => {
  assert.equal(toPascalCase('chevron-left'), 'ChevronLeft');
  assert.equal(toPascalCase('2fa-code'), '_2faCode');
});

test('renderRegistry emits the header, imports and the name union for icons', () => {
  const out = renderRegistry(icons, [
    { file: 'home.svg', name: 'home' },
    { file: 'chevron-left.svg', name: 'chevron-left' },
  ]);
  assert.match(out, /^\/\/ AUTO-GENERATED by scripts\/assets-sync\.mjs — do not edit\n/);
  assert.match(out, /import Home from '\.\/home\.svg';/);
  assert.match(out, /'chevron-left': ChevronLeft,/);
  assert.match(out, /export type IconName = keyof typeof icons;/);
});

test('renderRegistry uses require for images and an empty map when there are none', () => {
  assert.match(
    renderRegistry(images, [{ file: 'logo.png', name: 'logo' }]),
    /logo: require\('\.\/logo\.png'\),/,
  );
  assert.match(renderRegistry(images, []), /export const images = \{\} as const;/);
});

test('syncAssets writes registries from the folders and is idempotent', () => {
  const root = mkdtempSync(path.join(tmpdir(), 'assets-sync-'));
  for (const dir of ['icons', 'images', 'animations']) {
    mkdirSync(path.join(root, 'src', 'assets', dir), { recursive: true });
  }
  writeFileSync(path.join(root, 'src/assets/icons/user.svg'), '<svg />');
  writeFileSync(path.join(root, 'src/assets/animations/spinner.json'), '{}');
  assert.equal(syncAssets(root).length, 3);
  assert.match(readFileSync(path.join(root, 'src/assets/icons/index.ts'), 'utf8'), /user: User,/);
  assert.match(
    readFileSync(path.join(root, 'src/assets/animations/index.ts'), 'utf8'),
    /spinner: require\('\.\/spinner\.json'\),/,
  );
  assert.equal(syncAssets(root).length, 0);
});

test('listAssets rejects file names that could inject code or escape the folder', () => {
  const dir = mkdtempSync(path.join(tmpdir(), 'assets-unsafe-'));
  writeFileSync(path.join(dir, "a'); process.exit(1); ('.svg"), '<svg />');
  assert.throws(() => listAssets(dir, ['.svg']), /unsafe asset file name/);
});

test('assertSafeAsset rejects traversal, quotes and spaces but accepts normal names', () => {
  assert.throws(() => assertSafeAsset('../x.svg', '../x'), /unsafe asset file name/);
  assert.throws(() => assertSafeAsset('a b.svg', 'a b'), /unsafe asset file name/);
  assert.doesNotThrow(() => assertSafeAsset('chevron-left.svg', 'chevron-left'));
});

test('non-identifier keys and paths are emitted as escaped string literals', () => {
  const out = renderRegistry(icons, [{ file: 'eye-off.svg', name: 'eye-off' }]);
  assert.match(out, /import EyeOff from '\.\/eye-off\.svg';/);
  assert.match(out, /'eye-off': EyeOff,/);
});
